@app.post("/predict", response_model=PredictionResponse, tags=["Inference"])
async def predict_scan(
    file: UploadFile = File(..., description="NIfTI MRI file (.nii or .nii.gz)"),
) -> PredictionResponse:
    """Run volumetric 3D AI inference and Grad-CAM on uploaded NIfTI scan."""
    if predictor is None:
        raise HTTPException(
            status_code=status.HTTP_503_SERVICE_UNAVAILABLE,
            detail="AI inference engine is not ready.",
        )

    filename = file.filename or "scan.nii.gz"
    if not (filename.endswith(".nii") or filename.endswith(".nii.gz")):
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail="Invalid file format. Please upload a NIfTI file (.nii or .nii.gz).",
        )

    try:
        content = await file.read()
        logger.info("Received file '%s' (%d bytes) for inference.", filename, len(content))
        volume, zooms, _ = load_nifti_from_bytes(content, filename=filename)
        logger.info("Volume loaded: shape=%s, spacing=%s", volume.shape, zooms)

        result = predictor.predict(volume=volume, voxel_spacing=zooms)
        return result
    except ValueError as e:
        logger.info("Rejected invalid volume %s: %s", filename, e)
        raise HTTPException(
            status_code=status.HTTP_422_UNPROCESSABLE_ENTITY,
            detail=f"Invalid DCE-MRI input: {e}",
        ) from e
    except Exception as e:
        logger.error("Inference failed for file %s: %s", filename, e, exc_info=True)
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail=f"Inference error: {str(e)}",
        ) from e


@app.post("/predict-demo/{demo_id}", response_model=PredictionResponse, tags=["Inference"])
async def predict_demo_scan(demo_id: str) -> PredictionResponse:
    """Execute prediction on a built-in demo scan without needing client upload."""
    if predictor is None:
        raise HTTPException(status_code=503, detail="AI engine not loaded.")

    demo_map = {
        "synth-001": DATA_DIR / "segmentation_dryrun" / "subtraction" / "SYNTH_CASE_001_subtraction.nii.gz",
        "synth-002": DATA_DIR / "segmentation_dryrun" / "subtraction" / "SYNTH_CASE_002_subtraction.nii.gz",
    }

    target_path = demo_map.get(demo_id)
    if not target_path or not target_path.exists():
        raise HTTPException(status_code=404, detail=f"Demo scan '{demo_id}' not found.")

    logger.info("Running demo prediction on file: %s", target_path)
    volume, zooms, _ = load_nifti_from_path(str(target_path))
    return predictor.predict(volume=volume, voxel_spacing=zooms)


